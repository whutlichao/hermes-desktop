function requiresErrorTemplate(key: string): boolean {
  return (
    ERROR_TEMPLATE_KEYS.has(key as CopyKey) ||
    ((key.startsWith("terminal.") || key.startsWith("chat.")) && key.endsWith("Error"))
  );
}

export interface TerminologyViolation {
  key?: string;
  reason: string;
  text: string;
}

export function getCopy(key: CopyKey): string {
  return COPY_CATALOG[key];
}

export function validateTerminology(text: string, key?: string): TerminologyViolation[] {
  const violations: TerminologyViolation[] = [];
  const trimmed = text.trim();

  if (BANNED_BARE_BUTTONS.has(trimmed)) {
    violations.push({
      key,
      reason: `按钮文案禁止使用裸“${trimmed}”，请使用明确动词`,
      text,
    });
  }

  for (const banned of BANNED_TRANSLATIONS) {
    if (text.includes(banned)) {
      violations.push({
        key,
        reason: `发现禁止使用的旧中文译名“${banned}”，请保留固定英文术语`,
        text,
      });
    }
  }

  // Enforce single half-width space between CJK and ASCII alphanumeric (excluding standalone shortcuts like ⌘K)
  if (/[\u4e00-\u9fff][A-Za-z0-9]/.test(text) || /[A-Za-z0-9][\u4e00-\u9fff]/.test(text)) {
    violations.push({
      key,
      reason: "中文与英文/数字之间必须保留一个半角空格",
      text,
    });
  }

  // Chinese sentences must use full-width punctuation. ASCII punctuation directly adjacent to
  // CJK text is a mixed-typography regression; URL/CLI/code fragments are not adjacent to CJK.
  if (
    /[\u4e00-\u9fff][,.:;!?()[\]"']/.test(text) ||
    /[,.:;!?()[\]"'][\u4e00-\u9fff]/.test(text)
  ) {
    violations.push({
      key,
      reason: "中文句子必须使用全角标点，不能混用半角标点",
      text,
    });
  }

  if (/\.{3}/.test(text)) {
    violations.push({
      key,
      reason: "中文文案必须使用全角省略号“……”，不能使用 ASCII “...”",
      text,
    });
  }

  // Enforce canonical casing for the 10 fixed English terms when appearing as standalone words
  for (const term of CANONICAL_ENGLISH_TERMS) {
    const lowerRe = new RegExp(`\\b${term.toLowerCase()}\\b`, "g");
    const matches = text.match(lowerRe);
    if (matches) {
      for (const m of matches) {
        if (m !== term && m !== term.toUpperCase()) {
          violations.push({
            key,
            reason: `固定英文术语“${term}”大小写错误（发现“${m}”）`,
            text,
          });
        }
      }
    }
  }

  return violations;
}

export function lintCopyCatalog(
  catalog: Record<string, string | undefined>,
): TerminologyViolation[] {
  const violations: TerminologyViolation[] = [];
  for (const [key, value] of Object.entries(catalog)) {
    if (!value) {
      violations.push({
        key,
        reason: "文案缺失或为原始 key",
        text: "",
      });
      continue;
    }
    if (value.trim() === "" || value === key) {
      violations.push({
        key,
        reason: "文案缺失或为原始 key",
        text: value,
      });
      continue;
    }
    violations.push(...validateTerminology(value, key));
    if (requiresErrorTemplate(key)) {
      for (const label of ["发生了什么", "可能原因", "下一步"]) {
        if (!value.includes(label)) {
          violations.push({
            key,
            reason: `错误文案必须包含“${label}”`,
            text: value,
          });
        }
      }
    }
  }
  return violations;
}

export interface CopyLintSourceFile {
  path: string;
  content: string;
}

const ERROR_FACTORY_CALL =
  /\b(?:makeTurnError|makeBridgeError|createCodedError|new\s+Error)\s*\(/g;

function stripComments(content: string): string {
  let result = "";
  let quote: string | null = null;
  for (let cursor = 0; cursor < content.length; cursor += 1) {
    const char = content[cursor];
    if (quote) {
      result += char;
      if (char === "\\") {
        result += content.slice(cursor + 1, cursor + 2);
        cursor += 1;
      } else if (char === quote) {
        quote = null;
      }
      continue;
    }
    if (char === '"' || char === "'" || char === "`") {
      quote = char;
      result += char;
      continue;
    }
    if (char === "/" && content[cursor + 1] === "/") {
      while (cursor < content.length && content[cursor] !== "\n") {
        result += " ";
        cursor += 1;
      }
      result += "\n";
      continue;
    }
    if (char === "/" && content[cursor + 1] === "*") {
      result += "  ";
      cursor += 2;
      while (
        cursor < content.length &&
        !(content[cursor] === "*" && content[cursor + 1] === "/")
      ) {
        result += content[cursor] === "\n" ? "\n" : " ";
        cursor += 1;
      }
      result += "  ";
      cursor += 1;
      continue;
    }
    result += char;
  }
  return result;
}

function collectVisibleLiteralsInCall(content: string, start: number): string[] {
  const literals: string[] = [];
  let depth = 1;
  let cursor = start;
  while (cursor < content.length && depth > 0) {
    const char = content[cursor];
    if (char === '"' || char === "'" || char === "`") {
      const quote = char;
      const literalStart = cursor + 1;
      cursor = literalStart;
      while (cursor < content.length && content[cursor] !== quote) {
        cursor += content[cursor] === "\\" ? 2 : 1;
      }
      const literal = content.slice(literalStart, cursor);
      if (/[\u4e00-\u9fff]/.test(literal)) {
        literals.push(literal);
      }
      cursor += 1;
      continue;
    }
    if (char === "(") {
      depth += 1;
    } else if (char === ")") {
      depth -= 1;
    }
    cursor += 1;
  }
  return literals;
}

export function lintVisibleErrorLiterals(
  files: readonly CopyLintSourceFile[],
  allowedCounts: Readonly<Record<string, Readonly<Record<string, number>>>>,
): TerminologyViolation[] {
  const violations: TerminologyViolation[] = [];
  for (const file of files) {
    const counts = new Map<string, number>();
    const content = stripComments(file.content);
    for (const call of content.matchAll(ERROR_FACTORY_CALL)) {
      for (const literal of collectVisibleLiteralsInCall(
        content,
        call.index! + call[0].length,
      )) {
        counts.set(literal, (counts.get(literal) ?? 0) + 1);
      }
    }
    for (const [literal, count] of counts) {
      const allowed = allowedCounts[file.path]?.[literal] ?? 0;
      if (count > allowed) {
        violations.push({
          key: file.path,
          reason: `用户可见错误文案必须来自 copy catalog（新增 ${count - allowed} 处）`,
          text: literal,
        });
      }
    }
  }
  return violations;
}
